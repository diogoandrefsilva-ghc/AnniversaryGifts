-- =====================================================================
-- AnniversaryGifts — schema `anniversarygifts` (a app das prendas de anos).
-- Correr no SQL Editor do Supabase (o MESMO projeto das outras apps).
-- É IDEMPOTENTE: pode correr mais que uma vez sem erro.
--
-- Depois de correr: Settings → API → Exposed schemas → acrescentar
-- `anniversarygifts`. Sem isso o PostgREST responde 406/404 a tudo.
--
-- O MODELO, numa frase: cada amigo tem um dia de anos; ordenados pelo
-- calendário formam um CICLO, e quem faz anos imediatamente antes é quem
-- compra a garrafa para o seguinte. O custo divide-se por todos os outros
-- (incluindo quem compra), NUNCA por quem faz anos.
--
-- As escritas em `eventos` e `pagamentos` passam SÓ por funções SECURITY
-- DEFINER (mais abaixo): as regras de quem pode o quê vivem aqui, num sítio
-- só, e não em policies espalhadas. A leitura é aberta a quem tem acesso —
-- as dívidas são PÚBLICAS dentro do grupo, de propósito.
-- =====================================================================

CREATE SCHEMA IF NOT EXISTS anniversarygifts;
GRANT USAGE ON SCHEMA anniversarygifts TO anon, authenticated, service_role;

